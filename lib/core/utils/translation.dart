String toArabicDigits(String text) {
  const western = '0123456789';
  const arabic = '٠١٢٣٤٥٦٧٨٩';
  return text.split('').map((c) {
    final i = western.indexOf(c);
    return i >= 0 ? arabic[i] : c;
  }).join();
}

String trans(BuildContext context, String text) {
  if (text.isEmpty) return text;
  final trimmed = text.trim();
  final code = Localizations.localeOf(context).languageCode;

  if (code == 'en') return text;

  final map = _translations[code];
  if (map == null) return text;

  if (map.containsKey(trimmed)) {
    return map[trimmed]!;
  }

  if (text.contains(':')) {
    final parts = text.split(':');
    final field = parts[0].trim();
    final detail = parts.length > 1 ? parts.sublist(1).join(':').trim() : '';
    final transField = map[field] ?? field;
    final transDetail = map[detail] ?? detail;
    return '$transField: $transDetail';
  }

  return text;
}
